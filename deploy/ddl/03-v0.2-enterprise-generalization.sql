-- 不适用于新装 v0.2；新装请执行 00、01、02。
--
-- 重要：
--   1. 本脚本不删除、重命名或改写旧业务列，不会自动完成应用切流。
--   2. 新旧身份模型并存期间，应用必须双写并核对；切流/收缩另行评审。
--   3. embedding_dimension 与 model_revision 无法从 v0.1 可靠推断，迁移档案保持 DRAFT，
--      必须完成重建与质量门禁后才能激活。
--   4. 执行前必须备份、演练、统计行数并取得变更窗口批准。
-- =====================================================================

