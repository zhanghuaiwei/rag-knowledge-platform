-- 通用企业知识库平台 · PostgreSQL Schema（v0.2，新装基线）
-- 目标：PostgreSQL 16+
-- 权威设计：docs/04-数据库设计.md
--
-- 安全边界：
--   * tenant 资源使用 tenant_id + 复合外键阻止跨租户关联
--   * ragkb_owner 拥有对象；ragkb_app 仅 DML 且无 BYPASSRLS
--   * RLS 在应用设置 tenant context 后由 04-enable-tenant-rls.sql 启用
--   * 原文/密钥不存本 Schema；仅保存 object_key、secret_ref 或不可逆摘要
-- =====================================================================

\set ON_ERROR_STOP on
SET ROLE ragkb_owner;
BEGIN;

CREATE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- 1. Tenant / Identity -------------------------------------------------

CREATE TABLE sys_tenant (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(64)  NOT NULL,
    name             VARCHAR(128) NOT NULL,
    deployment_mode  VARCHAR(16)  NOT NULL DEFAULT 'SAAS',
    data_region      VARCHAR(64)  NOT NULL DEFAULT 'default',
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    policy_version   BIGINT       NOT NULL DEFAULT 1,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    row_version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_sys_tenant_code UNIQUE (code),
    CONSTRAINT ck_sys_tenant_code CHECK (code ~ '^[a-z0-9][a-z0-9_-]{1,63}$'),
    CONSTRAINT ck_sys_tenant_mode CHECK (deployment_mode IN ('SAAS', 'PRIVATE')),
    CONSTRAINT ck_sys_tenant_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELETING')),
    CONSTRAINT ck_sys_tenant_policy_version CHECK (policy_version >= 1)
);

CREATE TABLE sys_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primary_email    VARCHAR(254),
    display_name     VARCHAR(128),
    status           VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    last_login_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_sys_user_status CHECK (status IN ('ACTIVE', 'DISABLED', 'DELETED'))
);
CREATE UNIQUE INDEX uq_sys_user_primary_email
    ON sys_user (lower(primary_email)) WHERE primary_email IS NOT NULL;

CREATE TABLE identity_account (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES sys_user(id),
    protocol         VARCHAR(16)  NOT NULL,
    issuer           VARCHAR(512) NOT NULL,
    subject          VARCHAR(512) NOT NULL,
    email_at_link    VARCHAR(254),
    last_login_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_identity_issuer_subject UNIQUE (issuer, subject),
    CONSTRAINT ck_identity_protocol CHECK (protocol IN ('OIDC', 'SAML'))
);
CREATE INDEX idx_identity_account_user ON identity_account (user_id);

CREATE TABLE identity_provider (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES sys_tenant(id),
    provider_key     VARCHAR(64)  NOT NULL,
    protocol         VARCHAR(16)  NOT NULL,
    issuer           VARCHAR(512),
    discovery_uri    VARCHAR(1024),
    client_id        VARCHAR(256),
    secret_ref       VARCHAR(512),
    scopes           JSONB        NOT NULL DEFAULT '["openid","profile","email"]'::jsonb,
    config           JSONB        NOT NULL DEFAULT '{}'::jsonb,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    row_version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_identity_provider UNIQUE (tenant_id, provider_key),
    CONSTRAINT uq_identity_provider_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT ck_identity_provider_protocol CHECK (protocol IN ('OIDC', 'SAML')),
    CONSTRAINT ck_identity_provider_status CHECK (status IN ('ACTIVE', 'DISABLED', 'ERROR')),
    CONSTRAINT ck_identity_provider_scopes CHECK (jsonb_typeof(scopes) = 'array'),
    CONSTRAINT ck_identity_provider_config CHECK (jsonb_typeof(config) = 'object')
);

CREATE TABLE tenant_member (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT      NOT NULL REFERENCES sys_tenant(id),
    user_id          BIGINT      NOT NULL REFERENCES sys_user(id),
    status           VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    joined_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    suspended_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_tenant_member_user UNIQUE (tenant_id, user_id),
    CONSTRAINT uq_tenant_member_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT ck_tenant_member_status CHECK (status IN ('INVITED', 'ACTIVE', 'SUSPENDED'))
);
CREATE INDEX idx_tenant_member_user ON tenant_member (user_id, status);

CREATE TABLE tenant_member_role (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT      NOT NULL REFERENCES sys_tenant(id),
    user_id          BIGINT      NOT NULL,
    role             VARCHAR(32) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_tenant_member_role_member
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES tenant_member (tenant_id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_tenant_member_role UNIQUE (tenant_id, user_id, role),
    CONSTRAINT ck_tenant_member_role CHECK (
        role IN ('TENANT_ADMIN', 'SECURITY_ADMIN', 'KNOWLEDGE_ADMIN', 'AUDITOR', 'MEMBER')
    )
);

CREATE TABLE sys_org (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES sys_tenant(id),
    parent_id        BIGINT,
    external_id      VARCHAR(256),
    name             VARCHAR(128) NOT NULL,
    path             VARCHAR(2048) NOT NULL DEFAULT '/',
    source           VARCHAR(32)  NOT NULL DEFAULT 'LOCAL',
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    row_version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_sys_org_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_sys_org_sibling_name UNIQUE NULLS NOT DISTINCT (tenant_id, parent_id, name),
    CONSTRAINT fk_sys_org_parent
        FOREIGN KEY (tenant_id, parent_id)
        REFERENCES sys_org (tenant_id, id),
    CONSTRAINT ck_sys_org_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_sys_org_path CHECK (path LIKE '/%')
);
CREATE INDEX idx_sys_org_parent ON sys_org (tenant_id, parent_id, sort_order);
CREATE INDEX idx_sys_org_path ON sys_org (tenant_id, path text_pattern_ops);
CREATE UNIQUE INDEX uq_sys_org_external
    ON sys_org (tenant_id, source, external_id) WHERE external_id IS NOT NULL;

CREATE TABLE sys_user_org (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT      NOT NULL REFERENCES sys_tenant(id),
    user_id          BIGINT      NOT NULL,
    org_id           BIGINT      NOT NULL,
    source           VARCHAR(32) NOT NULL DEFAULT 'LOCAL',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_sys_user_org_member
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES tenant_member (tenant_id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_user_org_org
        FOREIGN KEY (tenant_id, org_id)
        REFERENCES sys_org (tenant_id, id) ON DELETE CASCADE,
    CONSTRAINT uq_sys_user_org UNIQUE (tenant_id, user_id, org_id)
);
CREATE INDEX idx_sys_user_org_org ON sys_user_org (tenant_id, org_id, user_id);

-- 2. Knowledge configuration -----------------------------------------

CREATE TABLE retention_policy (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES sys_tenant(id),
    name             VARCHAR(128) NOT NULL,
    scope_type       VARCHAR(24)  NOT NULL,
    scope_key        VARCHAR(128),
    retention_days   INTEGER      NOT NULL,
    disposition      VARCHAR(16)  NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    row_version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_retention_policy_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_retention_policy_name UNIQUE (tenant_id, name),
    CONSTRAINT ck_retention_scope CHECK (scope_type IN ('TENANT', 'KB', 'CLASSIFICATION')),
    CONSTRAINT ck_retention_days CHECK (retention_days > 0),
    CONSTRAINT ck_retention_disposition CHECK (disposition IN ('ARCHIVE', 'DELETE', 'REVIEW')),
    CONSTRAINT ck_retention_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE index_profile (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT       NOT NULL REFERENCES sys_tenant(id),
    name                  VARCHAR(128) NOT NULL,
    profile_version       INTEGER      NOT NULL,
    embedding_provider    VARCHAR(128) NOT NULL,
    embedding_model       VARCHAR(256) NOT NULL,
    model_revision        VARCHAR(256) NOT NULL,
    embedding_dimension   INTEGER      NOT NULL,
    normalization         VARCHAR(16)  NOT NULL DEFAULT 'L2',
    distance_metric       VARCHAR(16)  NOT NULL DEFAULT 'COSINE',
    chunker_config        JSONB        NOT NULL,
    analyzer_config       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    reranker_provider     VARCHAR(128),
    reranker_model        VARCHAR(256),
    status                VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    activated_at          TIMESTAMPTZ,
    retired_at            TIMESTAMPTZ,
    CONSTRAINT uq_index_profile_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_index_profile_version UNIQUE (tenant_id, name, profile_version),
    CONSTRAINT ck_index_profile_version CHECK (profile_version >= 1),
    CONSTRAINT ck_index_dimension CHECK (embedding_dimension BETWEEN 64 AND 65536),
    CONSTRAINT ck_index_normalization CHECK (normalization IN ('NONE', 'L2')),
    CONSTRAINT ck_index_metric CHECK (distance_metric IN ('COSINE', 'L2', 'INNER_PRODUCT')),
    CONSTRAINT ck_index_profile_status CHECK (status IN ('DRAFT', 'ACTIVE', 'RETIRED')),
    CONSTRAINT ck_index_chunker_json CHECK (jsonb_typeof(chunker_config) = 'object'),
    CONSTRAINT ck_index_analyzer_json CHECK (jsonb_typeof(analyzer_config) = 'object')
);

CREATE TABLE kb (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT       NOT NULL REFERENCES sys_tenant(id),
    data_region           VARCHAR(64)  NOT NULL DEFAULT 'default',
    name                  VARCHAR(128) NOT NULL,
    description           VARCHAR(1024),
    visibility            VARCHAR(16)  NOT NULL DEFAULT 'PRIVATE',
    status                VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    index_profile_id      BIGINT       NOT NULL,
    metadata_schema_id    BIGINT,
    retention_policy_id   BIGINT,
    requires_review       BOOLEAN      NOT NULL DEFAULT TRUE,
    ocr_enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    active_index_build_id BIGINT,
    policy_version        BIGINT       NOT NULL DEFAULT 1,
    created_by            BIGINT,
    updated_by            BIGINT,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at            TIMESTAMPTZ,
    row_version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_kb_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_kb_tenant_name UNIQUE (tenant_id, name),
    CONSTRAINT fk_kb_index_profile
        FOREIGN KEY (tenant_id, index_profile_id)
        REFERENCES index_profile (tenant_id, id),
    CONSTRAINT fk_kb_retention_policy
        FOREIGN KEY (tenant_id, retention_policy_id)
        REFERENCES retention_policy (tenant_id, id),
    CONSTRAINT ck_kb_visibility CHECK (visibility IN ('PRIVATE', 'TENANT')),
    CONSTRAINT ck_kb_status CHECK (status IN ('ACTIVE', 'ARCHIVED', 'DELETING', 'DELETED')),
    CONSTRAINT ck_kb_policy_version CHECK (policy_version >= 1),
    CONSTRAINT ck_kb_deleted_at CHECK (
        (status IN ('DELETING', 'DELETED') AND deleted_at IS NOT NULL)
        OR (status NOT IN ('DELETING', 'DELETED') AND deleted_at IS NULL)
    )
);
CREATE INDEX idx_kb_status ON kb (tenant_id, status, updated_at DESC);

CREATE TABLE kb_member (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT      NOT NULL REFERENCES sys_tenant(id),
    kb_id            BIGINT      NOT NULL,
    user_id          BIGINT      NOT NULL,
    role             VARCHAR(16) NOT NULL,
    created_by       BIGINT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT fk_kb_member_kb
        FOREIGN KEY (tenant_id, kb_id)
        REFERENCES kb (tenant_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_kb_member_user
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES tenant_member (tenant_id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_kb_member UNIQUE (tenant_id, kb_id, user_id),
    CONSTRAINT ck_kb_member_role CHECK (role IN ('OWNER', 'EDITOR', 'VIEWER'))
);
CREATE INDEX idx_kb_member_user ON kb_member (tenant_id, user_id, kb_id);

CREATE TABLE metadata_schema (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES sys_tenant(id),
    kb_id            BIGINT,
    name             VARCHAR(128) NOT NULL,
    schema_version   INTEGER      NOT NULL,
    schema_json      JSONB        NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    created_by       BIGINT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at     TIMESTAMPTZ,
    CONSTRAINT uq_metadata_schema_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_metadata_schema_version UNIQUE (tenant_id, kb_id, name, schema_version),
    CONSTRAINT fk_metadata_schema_kb
        FOREIGN KEY (tenant_id, kb_id)
        REFERENCES kb (tenant_id, id),
    CONSTRAINT ck_metadata_schema_version CHECK (schema_version >= 1),
    CONSTRAINT ck_metadata_schema_json CHECK (jsonb_typeof(schema_json) = 'object'),
    CONSTRAINT ck_metadata_schema_status CHECK (status IN ('DRAFT', 'ACTIVE', 'RETIRED'))
);

ALTER TABLE kb
    ADD CONSTRAINT fk_kb_metadata_schema
    FOREIGN KEY (tenant_id, metadata_schema_id)
    REFERENCES metadata_schema (tenant_id, id);

-- 3. Content source / sync / document --------------------------------

CREATE TABLE source_connection (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT        NOT NULL REFERENCES sys_tenant(id),
    kb_id            BIGINT        NOT NULL,
    name             VARCHAR(128)  NOT NULL,
    provider_key     VARCHAR(128)  NOT NULL,
    secret_ref       VARCHAR(512),
    config           JSONB         NOT NULL DEFAULT '{}'::jsonb,
    sync_mode        VARCHAR(16)   NOT NULL DEFAULT 'MANUAL',
    status           VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    cursor_value     TEXT,
    last_success_at  TIMESTAMPTZ,
    last_error_code  VARCHAR(64),
    last_error_at    TIMESTAMPTZ,
    created_by       BIGINT,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    row_version      BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_source_connection_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_source_connection_name UNIQUE (tenant_id, kb_id, name),
    CONSTRAINT fk_source_connection_kb
        FOREIGN KEY (tenant_id, kb_id)
        REFERENCES kb (tenant_id, id),
    CONSTRAINT ck_source_connection_config CHECK (jsonb_typeof(config) = 'object'),
    CONSTRAINT ck_source_connection_mode CHECK (sync_mode IN ('MANUAL', 'SCHEDULED', 'WEBHOOK')),
    CONSTRAINT ck_source_connection_status CHECK (status IN ('ACTIVE', 'PAUSED', 'ERROR', 'REVOKED'))
);
CREATE INDEX idx_source_connection_status ON source_connection (tenant_id, status, last_success_at);

CREATE TABLE sync_job (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES sys_tenant(id),
    connection_id    BIGINT       NOT NULL,
    job_type         VARCHAR(16)  NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'QUEUED',
    idempotency_key  VARCHAR(128) NOT NULL,
    cursor_before    TEXT,
    cursor_after     TEXT,
    discovered_count INTEGER      NOT NULL DEFAULT 0,
    created_count    INTEGER      NOT NULL DEFAULT 0,
    updated_count    INTEGER      NOT NULL DEFAULT 0,
    deleted_count    INTEGER      NOT NULL DEFAULT 0,
    failed_count     INTEGER      NOT NULL DEFAULT 0,
    error_code       VARCHAR(64),
    error_detail     JSONB,
    queued_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at       TIMESTAMPTZ,
    finished_at      TIMESTAMPTZ,
    CONSTRAINT uq_sync_job_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_sync_job_idempotency UNIQUE (tenant_id, connection_id, idempotency_key),
    CONSTRAINT fk_sync_job_connection
        FOREIGN KEY (tenant_id, connection_id)
        REFERENCES source_connection (tenant_id, id),
    CONSTRAINT ck_sync_job_type CHECK (job_type IN ('FULL', 'INCREMENTAL', 'WEBHOOK', 'RECONCILE')),
    CONSTRAINT ck_sync_job_status CHECK (status IN ('QUEUED', 'RUNNING', 'PARTIAL', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_sync_job_counts CHECK (
        discovered_count >= 0 AND created_count >= 0 AND updated_count >= 0
        AND deleted_count >= 0 AND failed_count >= 0
    ),
    CONSTRAINT ck_sync_job_error_json CHECK (error_detail IS NULL OR jsonb_typeof(error_detail) = 'object')
);
CREATE INDEX idx_sync_job_queue ON sync_job (tenant_id, status, queued_at);

CREATE TABLE source_object (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT        NOT NULL REFERENCES sys_tenant(id),
    connection_id      BIGINT        NOT NULL,
    external_id        VARCHAR(1024) NOT NULL,
    source_uri         VARCHAR(2048),
    source_version     VARCHAR(512),
    source_etag        VARCHAR(512),
    content_sha256     CHAR(64),
    source_acl         JSONB         NOT NULL DEFAULT '{}'::jsonb,
    document_id        BIGINT,
    last_sync_job_id   BIGINT,
    tombstoned         BOOLEAN       NOT NULL DEFAULT FALSE,
    source_updated_at  TIMESTAMPTZ,
    last_seen_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    row_version        BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_source_object_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_source_object_external UNIQUE (tenant_id, connection_id, external_id),
    CONSTRAINT fk_source_object_connection
        FOREIGN KEY (tenant_id, connection_id)
        REFERENCES source_connection (tenant_id, id),
    CONSTRAINT fk_source_object_sync_job
        FOREIGN KEY (tenant_id, last_sync_job_id)
        REFERENCES sync_job (tenant_id, id),
    CONSTRAINT ck_source_object_sha CHECK (content_sha256 IS NULL OR content_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_source_object_acl CHECK (jsonb_typeof(source_acl) = 'object')
);
CREATE INDEX idx_source_object_document ON source_object (tenant_id, document_id);
CREATE INDEX idx_source_object_tombstone ON source_object (tenant_id, connection_id, tombstoned, last_seen_at);

CREATE TABLE document (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT        NOT NULL REFERENCES sys_tenant(id),
    kb_id               BIGINT        NOT NULL,
    title               VARCHAR(512)  NOT NULL,
    file_name           VARCHAR(512),
    file_ext            VARCHAR(32),
    mime_type           VARCHAR(256),
    source_type         VARCHAR(64)   NOT NULL DEFAULT 'UPLOAD',
    source_uri          VARCHAR(2048),
    owner_user_id       BIGINT,
    lifecycle_status    VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    review_status       VARCHAR(24)   NOT NULL DEFAULT 'DRAFT',
    authority_status    VARCHAR(24)   NOT NULL DEFAULT 'DRAFT',
    sensitivity         VARCHAR(24)   NOT NULL DEFAULT 'INTERNAL',
    data_region         VARCHAR(64),
    current_version_id  BIGINT,
    valid_from          TIMESTAMPTZ,
    valid_until         TIMESTAMPTZ,
    review_due_at       TIMESTAMPTZ,
    is_disabled         BOOLEAN       NOT NULL DEFAULT FALSE,
    policy_version      BIGINT        NOT NULL DEFAULT 1,
    created_by          BIGINT,
    updated_by          BIGINT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,
    row_version         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_document_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_document_kb
        FOREIGN KEY (tenant_id, kb_id)
        REFERENCES kb (tenant_id, id),
    CONSTRAINT fk_document_owner
        FOREIGN KEY (tenant_id, owner_user_id)
        REFERENCES tenant_member (tenant_id, user_id),
    CONSTRAINT ck_document_lifecycle CHECK (lifecycle_status IN ('ACTIVE', 'ARCHIVED', 'DELETING', 'DELETED')),
    CONSTRAINT ck_document_review CHECK (review_status IN ('DRAFT', 'PENDING_REVIEW', 'PUBLISHED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_document_authority CHECK (authority_status IN ('DRAFT', 'AUTHORITATIVE', 'SUPERSEDED')),
    CONSTRAINT ck_document_sensitivity CHECK (sensitivity IN ('PUBLIC', 'INTERNAL', 'CONFIDENTIAL', 'RESTRICTED')),
    CONSTRAINT ck_document_valid_range CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until > valid_from),
    CONSTRAINT ck_document_policy_version CHECK (policy_version >= 1),
    CONSTRAINT ck_document_deleted_at CHECK (
        (lifecycle_status IN ('DELETING', 'DELETED') AND deleted_at IS NOT NULL)
        OR (lifecycle_status NOT IN ('DELETING', 'DELETED') AND deleted_at IS NULL)
    )
);
CREATE INDEX idx_document_retrievable
    ON document (tenant_id, kb_id, lifecycle_status, review_status, is_disabled, updated_at DESC);
CREATE INDEX idx_document_review_due
    ON document (tenant_id, review_due_at) WHERE review_due_at IS NOT NULL;

CREATE TABLE document_version (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT        NOT NULL REFERENCES sys_tenant(id),
    document_id        BIGINT        NOT NULL,
    version_no         INTEGER       NOT NULL,
    object_key         VARCHAR(1024) NOT NULL,
    content_sha256     CHAR(64)      NOT NULL,
    source_version     VARCHAR(512),
    file_size          BIGINT        NOT NULL,
    mime_type          VARCHAR(256)  NOT NULL,
    language           VARCHAR(32),
    ingest_status      VARCHAR(24)   NOT NULL DEFAULT 'QUARANTINED',
    safety_status      VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    safety_report      JSONB,
    parser_profile     VARCHAR(128),
    parser_revision    VARCHAR(128),
    chunk_count        INTEGER       NOT NULL DEFAULT 0,
    error_code         VARCHAR(64),
    error_detail       JSONB,
    created_by         BIGINT,
