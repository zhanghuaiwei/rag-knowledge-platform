-- 10. updated_at triggers --------------------------------------------

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'sys_tenant', 'sys_user', 'identity_account', 'identity_provider',
        'tenant_member', 'sys_org', 'retention_policy', 'kb', 'kb_member',
        'source_connection', 'source_object', 'document', 'document_metadata',
        'chat_session', 'usage_daily', 'model_route_config', 'idempotency_record',
        'deletion_target', 'webhook_subscription', 'webhook_delivery'
    ]
    LOOP
        EXECUTE format(
            'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I '
            'FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
            table_name, table_name
        );
    END LOOP;
END;
$$;

